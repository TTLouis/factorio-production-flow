"""Generate the Sankey ribbon sprite atlas + shared step table.

Each ribbon lives in a unit box. Vertical thickness r (fraction of box height),
vertical drop 1-r. Top edge follows the d3-sankey cubic Bezier
  P0=(0,0) P1=(.5,0) P2=(.5,1-r) P3=(1,1-r)
so a runtime ribbon is fully described by (direction, r) and stretched to its box.

r is sampled geometrically so relative thickness error is constant (~±4.5%).

Run from the mod root:  python tools/gen_atlas.py
Outputs: graphics/ribbons.png, shared/ribbon_steps.lua
"""
import math
import os
import numpy as np
from PIL import Image

STEPS = 64            # shapes per direction
R_MIN = 0.004         # thinnest ratio (t / box height)
CELL_W, CELL_H = 384, 256   # wide: horizontal stretching is what causes saw-tooth edges
GRID_COLS = 10        # 128 cells -> 10 x 13 grid -> 3840 x 3328
SS = 4                # supersampling per axis

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATIO = (1.0 / R_MIN) ** (1.0 / (STEPS - 1))
R_VALUES = [R_MIN * RATIO ** k for k in range(STEPS)]
R_VALUES[-1] = 1.0


def bezier_top(xs):
    """y_top/drop as a function of x for the sankey cubic (invert x(u) numerically)."""
    u = np.linspace(0.0, 1.0, 4097)
    xu = 1.5 * u * (1 - u) + u ** 3          # x(u) with control x = 0.5
    yu = 3 * u ** 2 - 2 * u ** 3             # y(u) normalised
    return np.interp(xs, xu, yu)


# Elbows for orthogonal ("metro") routing of steep ribbons: a quarter annulus whose
# centre sits in one box corner. The box is (R + t) square, q = t / (R + t).
# Always drawn at ~1:1 (square cells, square boxes) so they stay crisp.
ELB = 128
ELB_STEPS = 32
ELB_Q = [0.06 + (0.94 - 0.06) * i / (ELB_STEPS - 1) for i in range(ELB_STEPS)]
ELB_CORNERS = ["bl", "tr", "tl", "br"]   # where the arc centre sits
ELB_GRID = 16


def render_elbow(q, corner):
    n = ELB * SS
    c = (np.arange(n) + 0.5) / n
    xs, ys = np.meshgrid(c, c)            # ys grows downward
    cx = 0.0 if corner in ("bl", "tl") else 1.0
    cy = 1.0 if corner in ("bl", "br") else 0.0
    d = np.sqrt((xs - cx) ** 2 + (ys - cy) ** 2)
    m = (d >= 1.0 - q) & (d <= 1.0)
    cov = m.reshape(ELB, SS, ELB, SS).mean(axis=(1, 3))
    return (cov * 255.0 + 0.5).astype(np.uint8)


def render_cell(r, cw=CELL_W, ch=CELL_H):
    w, h = cw * SS, ch * SS
    xs = (np.arange(w) + 0.5) / w
    ys = (np.arange(h) + 0.5) / h
    top = (1.0 - r) * bezier_top(xs)                 # shape (w,)
    inside = (ys[:, None] >= top[None, :]) & (ys[:, None] <= top[None, :] + r)
    cov = inside.reshape(ch, SS, cw, SS).mean(axis=(1, 3))
    return (cov * 255.0 + 0.5).astype(np.uint8)


def main():
    rows = math.ceil(2 * STEPS / GRID_COLS)
    alpha = np.zeros((rows * CELL_H, GRID_COLS * CELL_W), dtype=np.uint8)
    for i, r in enumerate(R_VALUES):
        cell = render_cell(r)
        for d, img in ((0, cell), (1, cell[::-1, :])):   # 0 = down, 1 = up (flipped)
            idx = d * STEPS + i
            cx, cy = (idx % GRID_COLS) * CELL_W, (idx // GRID_COLS) * CELL_H
            alpha[cy:cy + CELL_H, cx:cx + CELL_W] = img
    rgba = np.zeros(alpha.shape + (4,), dtype=np.uint8)
    rgba[..., :3] = 255
    rgba[..., 3] = alpha
    Image.fromarray(rgba, "RGBA").save(os.path.join(ROOT, "graphics", "ribbons.png"), optimize=True)

    # elbow atlas
    ncell = ELB_STEPS * len(ELB_CORNERS)
    erows = math.ceil(ncell / ELB_GRID)
    ea = np.zeros((erows * ELB, ELB_GRID * ELB), dtype=np.uint8)
    for ci, corner in enumerate(ELB_CORNERS):
        for i, q in enumerate(ELB_Q):
            idx = ci * ELB_STEPS + i
            x, y = (idx % ELB_GRID) * ELB, (idx // ELB_GRID) * ELB
            ea[y:y + ELB, x:x + ELB] = render_elbow(q, corner)
    erg = np.zeros(ea.shape + (4,), dtype=np.uint8)
    erg[..., :3] = 255
    erg[..., 3] = ea
    Image.fromarray(erg, "RGBA").save(os.path.join(ROOT, "graphics", "elbows.png"), optimize=True)

    with open(os.path.join(ROOT, "shared", "ribbon_steps.lua"), "w") as f:
        f.write("-- GENERATED by tools/gen_atlas.py - do not edit\n")
        f.write("return {\n")
        f.write(f"  count = {STEPS},\n  rmin = {R_MIN!r},\n  ratio = {RATIO!r},\n")
        f.write(f"  cell_w = {CELL_W},\n  cell_h = {CELL_H},\n  grid_cols = {GRID_COLS},\n")
        f.write("  r = {" + ", ".join(f"{v:.6f}" for v in R_VALUES) + "},\n")
        f.write(f"  elbow = {ELB},\n  elbow_steps = {ELB_STEPS},\n  elbow_grid = {ELB_GRID},\n")
        f.write("  elbow_q = {" + ", ".join(f"{v:.5f}" for v in ELB_Q) + "},\n")
        f.write("  elbow_corners = {" + ", ".join(f'"{c}"' for c in ELB_CORNERS) + "},\n")
        f.write("}\n")
    print(f"atlas {GRID_COLS * CELL_W}x{rows * CELL_H}, {2 * STEPS} cells, ratio step {RATIO:.4f}")


if __name__ == "__main__":
    main()
